import { chromium } from 'playwright';
const B = 'http://localhost:3000';
const browser = await chromium.launch({ headless: true, args: ['--headless=new'] });
const p = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage();
p.on('console', (m) => { if (m.type() === 'error') console.log('PAGE ERROR:', m.text().slice(0, 200)); });
p.on('pageerror', (e) => console.log('PAGE EXCEPTION:', String(e).slice(0, 300)));
await p.goto(B + '/', { waitUntil: 'load' });
await p.waitForTimeout(1200);
await p.evaluate(() => localStorage.setItem('stim:profile:guest', JSON.stringify({ id:'guest',userId:'guest',name:'N',avatarColor:'#000',level:'B1',goal:'ielts',accentTarget:'neutral',dailyGoalMin:15,availableMinPerDay:25,ieltsModule:'academic',uiLanguage:'en',plan:'free',createdAt:new Date().toISOString(),onboardingCompleted:true })));
await p.goto(B + '/ielts/writing', { waitUntil: 'load' });
await p.waitForTimeout(1000);
await p.locator('button.card').first().click();
await p.waitForTimeout(500);
await p.locator('textarea').fill('There is considerable disagreement about whether governments should fund the arts. This essay will examine both perspectives before concluding that public funding remains essential, because culture is not a luxury but infrastructure. Firstly, state funding allows access for citizens of every income level. Secondly, private sponsorship tends to favour popular forms. However, critics argue that taxpayers should not subsidise niche exhibitions. In conclusion, oversight is necessary.');
await p.getByRole('button', { name: /Get examiner report/ }).click();
await p.waitForTimeout(3000);
const t = await p.evaluate(() => document.body.innerText);
console.log('HAS improvements heading:', t.includes('Prioritised improvements'));
console.log('HAS exercise link:', t.includes('Targeted exercise'));
console.log('HAS evidence:', t.includes('Examiner evidence'));
const idx = t.indexOf('Examiner evidence');
console.log('--- text after evidence:', JSON.stringify(t.slice(idx, idx + 400)));
await browser.close();
